#!/usr/bin/env python3
"""
產生共用「節」(12 個月令交接) 時刻表，Python 與 TypeScript 引擎讀同一份，確保月柱/年柱一致。

輸出：
  shared/solar_terms_table.json                    — 正本（含 meta）
  frontend/src/data/solarTermsTable.ts             — 由正本自動生成（請勿手改）

表格式：JIE[i]，i=0 為 1899 年立春(寅)；之後每 12 項為一個八字年（立春起，至隔年小寒止）。
  branch = ORDER[i % 12]，ORDER=寅卯辰巳午未申酉戌亥子丑；bazi_year = 1899 + i // 12；i % 12 == 0 即立春。
時刻為北京時間(UTC+8)，格式 YYYYMMDDHHMM（四捨五入到分鐘）。支援出生日 1900-01-01 至 2100-12-31。

精度：目前由 solar_terms.py（低精度 Meeus 公式，實測與公佈值差約 4–8 分鐘）計算。
日後換成更高精度來源（如香港天文台資料／VSOP87 星曆）只需重新產生此表，引擎程式碼不用改。
"""
import json, os, sys, hashlib
from datetime import timedelta
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, 'backend'))
from app.engine.solar_terms import get_solar_term_time, JIE_QI_MONTH_MAP

FIRST, LAST = 1899, 2100          # 八字年範圍（涵蓋 1900-01-01 .. 2100-12-31）
def fmt(utc_dt):
    t = utc_dt + timedelta(hours=8, seconds=30)       # +30s = 四捨五入到分鐘
    return t.strftime('%Y%m%d%H%M')

jie = []
for y in range(FIRST, LAST + 1):
    for name, branch, angle in JIE_QI_MONTH_MAP:
        jie.append(fmt(get_solar_term_time(y, angle)))
assert len(jie) == (LAST - FIRST + 1) * 12
assert all(a < b for a, b in zip(jie, jie[1:])), 'table must be strictly increasing'

meta = {
  'description': '12 jie (month-boundary solar terms), Beijing time UTC+8, YYYYMMDDHHMM',
  'index_rule': 'JIE[i]: i%12==0 is Lichun(寅); branch=ORDER[i%12]; bazi_year=first_bazi_year+i//12',
  'order': '寅卯辰巳午未申酉戌亥子丑',
  'first_bazi_year': FIRST, 'last_bazi_year': LAST,
  'supported_birth_range': ['1900-01-01', '2100-12-31'],
  'algorithm': 'meeus-low-precision (backend/app/engine/solar_terms.py)',
  'known_precision': 'about 4-8 minutes vs published almanac values; NOT validated against authoritative source yet',
  'timezone': 'UTC+8 fixed (no historical timezone / DST / true solar time)',
  'table_version': '0.1-draft',
}
meta['sha256'] = hashlib.sha256(','.join(jie).encode()).hexdigest()
out = {'meta': meta, 'jie': jie}
with open(os.path.join(ROOT, 'shared', 'solar_terms_table.json'), 'w', encoding='utf-8') as f:
    json.dump(out, f, ensure_ascii=False, indent=1)
ts = ('// AUTO-GENERATED by tools/gen_solar_term_table.py from shared/solar_terms_table.json — DO NOT EDIT BY HAND\n'
      f'// table_version {meta["table_version"]}, sha256 {meta["sha256"]}\n'
      f'export const JIE_TABLE_META = {json.dumps(meta, ensure_ascii=False)} as const;\n'
      'export const JIE_TABLE: string[] = [\n' +
      ''.join('  ' + ', '.join(f'"{v}"' for v in jie[i:i+12]) + ',\n' for i in range(0, len(jie), 12)) + '];\n')
with open(os.path.join(ROOT, 'frontend', 'src', 'data', 'solarTermsTable.ts'), 'w', encoding='utf-8') as f:
    f.write(ts)
print('entries', len(jie), 'first', jie[0], 'last', jie[-1], 'sha256', meta['sha256'][:12])
