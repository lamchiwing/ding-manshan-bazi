def determine_favorable_elements_by_score(scoring_result: Dict[str, Any], bazi_result: Dict[str, Any]) -> Tuple[str, str, str, str, str]:
    """
    根據 100 分量化結果嚴格判定 5 個層級：
    1. 主要有利 (喜)
    2. 次要有利
    3. 中性
    4. 次要不利
    5. 主要不利 (忌)
    """
    scores = scoring_result["scores"]
    is_strong = scoring_result["is_strong"]
    day_stem = bazi_result["day_master"]["stem"]
    month_branch = bazi_result["pillars"]["month"]["branch"]
    
    # 調候優先判定主要元素
    if month_branch in ["亥", "子", "丑"] and day_stem in ["壬", "癸"]:
        primary = "火"
        secondary = "木"
    elif month_branch in ["巳", "午", "未"] and day_stem in ["丙", "丁"]:
        primary = "水"
        secondary = "金"
    elif month_branch in ["申", "酉", "戌"] and day_stem in ["庚", "辛"]:
        primary = "木"
        secondary = "水"
    elif month_branch in ["寅", "卯", "辰"] and day_stem in ["甲", "乙"]:
        primary = "金"
        secondary = "濕土"
    elif is_strong:
        # 身強取最低分非印比元素
        sorted_elems = sorted(scores.items(), key=lambda x: x[1])
        primary = sorted_elems[0][0]
        secondary = sorted_elems[1][0]
    else:
        # 身弱取生日主或同日主元素
        primary = "木" if day_stem in ["丙", "丁"] else "水"
        secondary = "金"

    matrix = FIVE_ELEMENTS_MATRIX.get(primary, FIVE_ELEMENTS_MATRIX["火"])
    return primary, matrix["次要有利五行"], matrix["中性五行"], matrix["次要不利五行"], matrix["主要不利五行"]

